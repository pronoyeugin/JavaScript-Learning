/* JSON Basic Stucture - Object and Array 

    object 
    {
        "key" : "value",
        "key" : "value",
        "key" : "value"
    }


    array 
    [
        "value",
        "value",
        "value"
    ]

*/


/* JSON syntax rules :
    1. Data is in name/value pairs
    2. Data is separated by commas
    3. Curly braces hold objects
    4. Square brackets hold arrays 

    {
        "name" : "John",
        "age" : 30,
        "city" : "New York"
    }

    [
        "John",
        "Jane",
        "Doe"
    ]

*/


/* JSON value type :
    1. String
    2. Number
    3. Object
    4. Array
    5. Boolean
    6. Null


    String: 
    {
        "name" : "Pronoy Eugin",
        "city" : "Dhaka"

    }

    Number:
    {
        "age" : 28,
        "height" : 5.7
    }

    Object:
    {
        "person" : {
            "name" : "Pronoy Eugin",
            "age" : 28,
            "city" : "Dhaka"
        }
    }

    Array:
    {
        "user" : 
            [ 
                "Pronoy",
                "Eugin", 
                "Khalko"
            ]
    }

    Boolean:
    {
        "isStudent" : true,
        "isEmployed" : false
    }

    Null:
    {
        "middleName" : null
    }

*/


